/** 프롬프트·파싱에서 공통으로 쓰는 섹션 정의 (순서 고정) */
export const SAJU_SECTIONS = [
  { id: 'chart', title: '사주 명식' },
  { id: 'personality', title: '성격과 기질' },
  { id: 'career', title: '재물과 일' },
  { id: 'relationship', title: '연애와 관계' },
  { id: 'strength', title: '돋보이는 특징' },
  { id: 'weakness', title: '약점' },
  { id: 'unique', title: '특이한 점' },
  { id: 'fortuneSummary', title: '운세 한줄 요약' },
]

/**
 * 사주 기본차트 해석 프롬프트
 * Gemini가 고정 섹션 형식으로만 답하도록 요청합니다.
 */
export function buildBasicChartPrompt({
  name,
  gender,
  calendar,
  birth,
  time,
}) {
  const sectionGuide = SAJU_SECTIONS.map(
    (s) => `[SECTION:${s.title}]\n(${sectionHint(s.id)})`,
  ).join('\n\n')

  return `당신은 세계 최고의 사주 해석 전문가다. 논리와 구조 중심으로 해석하며,
수천 명의 인생을 분석해 온 경험이 있다. 매우 냉정하고 직설적이지만,
인간 내면에 대한 깊은 통찰로 장점과 단점을 모두 말한다.

아래 출생 정보로 사주 명식을 세운 뒤, 이 사람의 성격·기질·재능·재물·관계까지 종합 분석하라.
사주 용어에 익숙하지 않다고 가정하고, 쉽고 명확하게 쓰되 핵심 근거는 밝혀라.

출생 정보: 이름 ${name} / 성별 ${gender} / ${calendar} ${birth} ${time}생

=== 해석 깊이 규칙 (반드시 지킬 것) ===
- 일간을 중심으로 성격의 뼈대를 설명하라.
- 월지(월령)가 성격·직업 성향에 미치는 영향을 언급하라.
- 오행이 많거나 없는 것이 주는 성향을 설명하라.
- 십신 1~2개를 골라 이 사람의 행동 패턴과 연결하라.
- 각 해석 섹션마다 "어떤 사주 요소 때문에 그런지" 근거 1문장 + "일상에서 어떻게 드러나는지" 예시 1문장을 넣어라.
- 긍정과 부정을 균형 있게 다루라. 추상적 형용사만 나열하지 마라.

=== 출력 규칙 (반드시 지킬 것) ===
1. 한국어로만 작성한다.
2. 아래 8개 섹션을 순서대로, 빠짐없이 작성한다.
3. 각 섹션은 반드시 [SECTION:제목] 한 줄로 시작하고, 그 다음 줄부터 본문을 쓴다.
4. 섹션 사이에는 빈 줄을 하나 넣는다.
5. 번호(1), 2)), ##, **, 서론, 마무리 멘트, "알겠습니다" 같은 잡담은 쓰지 않는다.
6. 해석 섹션(성격·재물·관계·특징·약점·특이점)은 각 5~8문장으로 충분히 쓴다.
7. 사주 명식은 6~10줄로 구조 정보를 명확히 정리한다.
8. 마지막 "운세 한줄 요약"은 질문 없이, 재물운·연애운·건강운·올해운을 각 1문장씩만 쓴다.

=== 출력 형식 (그대로 따를 것) ===
${sectionGuide}

위 형식 외의 다른 텍스트는 출력하지 마라.`
}

function sectionHint(id) {
  switch (id) {
    case 'chart':
      return '년·월·일·시주, 일간, 월령, 오행 분포(과다/부족), 십신 핵심을 6~10줄로 정리'
    case 'personality':
      return '전반적 성격·기질·재능. 일간·월령·십신 근거 + 일상 예시. 대인관계·일 스타일·스트레스 반응 포함. 5~8문장'
    case 'career':
      return '돈·일·커리어 성향. 맞는 일 방식, 재물 흐름의 장단점, 사주 근거 + 일상 예시. 5~8문장'
    case 'relationship':
      return '연애·대인관계 패턴, 맞는 상대 유형, 관계에서 반복되는 태도. 사주 근거 + 일상 예시. 5~8문장'
    case 'strength':
      return '돋보이는 강점 1가지를 깊게. 어떤 분야·역할에서 빛나는지, 근거 + 예시. 5~8문장'
    case 'weakness':
      return '약점과 반복 실수 패턴을 솔직·냉정하게. 주의할 상황 포함. 근거 + 예시. 5~8문장'
    case 'unique':
      return '일반적이지 않은 조합이나 눈에 띄는 구조 1가지. 근거 + 예시. 5~8문장'
    case 'fortuneSummary':
      return '아래 4줄만 출력. 질문 금지. 형식: "재물운: ..." / "연애운: ..." / "건강운: ..." / "올해운: ..." 각 1문장'
    default:
      return ''
  }
}
