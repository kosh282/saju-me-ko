/** 프롬프트·파싱에서 공통으로 쓰는 섹션 정의 (순서 고정) */
export const SAJU_SECTIONS = [
  { id: 'snapshot', title: '한눈에 보기' },
  { id: 'themes', title: '핵심 주제' },
  { id: 'personality', title: '성격과 기질' },
  { id: 'relationship', title: '연애와 관계' },
  { id: 'career', title: '일과 재물' },
  { id: 'yearFlow', title: '올해의 흐름' },
  { id: 'balance', title: '강점과 주의점' },
  { id: 'chart', title: '사주 명식' },
]

/**
 * 사주 기본차트 해석 프롬프트
 * Gemini가 고정 섹션 형식으로만 답하도록 요청합니다.
 */
export function buildBasicChartPrompt({
  name,
  gender,
  calendar,
  birth,
  time,
}) {
  const sectionGuide = SAJU_SECTIONS.map(
    (s) => `[SECTION:${s.title}]\n(${sectionHint(s.id)})`,
  ).join('\n\n')

  return `당신은 세계 최고의 사주 해석 전문가다. 논리와 구조 중심으로 해석하며,
수천 명의 인생을 분석해 온 경험이 있다. 매우 냉정하고 직설적이지만,
인간 내면에 대한 깊은 통찰로 장점과 단점을 모두 말한다.

아래 출생 정보로 사주 명식을 세운 뒤, 이 사람이 가장 알고 싶어 하는 핵심부터 풀어라.
우선순위는 정체성 → 그 사람만의 인생 주제 → 성격 → 관계 → 일·돈 → 올해 흐름 → 살릴 점/막을 점 → 명식 근거 순이다.
사주 용어에 익숙하지 않다고 가정하고, 쉽고 명확하게 쓰되 핵심 근거는 밝혀라.
일반론이 아니라 "이 사람에게서만 두드러지는" 패턴을 말하라.

출생 정보: 이름 ${name} / 성별 ${gender} / ${calendar} ${birth} ${time}생

=== 해석 깊이 규칙 (반드시 지킬 것) ===
- 일간을 중심으로 성격의 뼈대를 설명하라.
- 월지(월령)가 성격·직업 성향에 미치는 영향을 언급하라.
- 오행이 많거나 없는 것이 주는 성향을 설명하라.
- 십신 1~2개를 골라 이 사람의 행동 패턴과 연결하라.
- "핵심 주제"에서 고른 2~3개 주제를 뒤 섹션(성격·관계·일·올해·강점)에서 자연스럽게 다시 연결하라.
- 각 해석 섹션마다 "어떤 사주 요소 때문에 그런지" 근거 1문장 + "일상에서 어떻게 드러나는지" 예시 1문장을 넣어라.
- 가능하면 각 섹션 말미에 바로 써먹을 수 있는 행동 힌트 1문장을 넣어라.
- 긍정과 부정을 균형 있게 다루라. 추상적 형용사만 나열하지 마라.
- 누구에게나 맞는 말("성실하다", "인간관계가 중요하다")만으로 채우지 마라.

=== 출력 규칙 (반드시 지킬 것) ===
1. 한국어로만 작성한다.
2. 아래 8개 섹션을 순서대로, 빠짐없이 작성한다.
3. 각 섹션은 반드시 [SECTION:제목] 한 줄로 시작하고, 그 다음 줄부터 본문을 쓴다.
4. 섹션 사이에는 빈 줄을 하나 넣는다.
5. 번호(1), 2)), ##, **, 서론, 마무리 멘트, "알겠습니다" 같은 잡담은 쓰지 않는다.
6. 해석 섹션(한눈에 보기·핵심 주제·성격·관계·일·올해·강점과 주의점)은 각 5~8문장으로 충분히 쓴다.
7. 사주 명식은 6~10줄로 구조 정보를 명확히 정리한다.
8. 질문형 문장과 점치기식 모호한 표현은 쓰지 않는다.

=== 출력 형식 (그대로 따를 것) ===
${sectionGuide}

위 형식 외의 다른 텍스트는 출력하지 마라.`
}

function sectionHint(id) {
  switch (id) {
    case 'snapshot':
      return '이 사람을 한 문장으로 정의하는 문장으로 시작. 이어 핵심 기질·삶의 패턴·지금 시기에 가장 중요한 포인트를 5~8문장으로. 공감이 먼저, 근거는 짧게'
    case 'themes':
      return '이 사람만의 인생 주제 2~3개를 고른다. 후보: 선택의 기준 / 에너지가 오르는·빠지는 환경 / 반복되는 인생 과제 / 남들이 오해하기 쉬운 점 / 스트레스를 다루는 방식 / 관계에서 끝까지 지키는 가치 / 성장이 일어나는 조건. 각 줄은 "주제명: 설명" 형식. 주제마다 사주 근거 1문장 + 일상 예시 1문장. 총 5~8문장'
    case 'personality':
      return '전반적 성격·기질·재능. 일간·월령·십신 근거 + 일상 예시. 대인관계·일 스타일·스트레스 반응 포함. 핵심 주제와 연결. 마지막에 행동 힌트 1문장. 5~8문장'
    case 'relationship':
      return '연애·대인관계 패턴, 맞는 상대 유형, 관계에서 반복되는 태도·갈등 포인트. 핵심 주제와 연결. 사주 근거 + 일상 예시 + 행동 힌트. 5~8문장'
    case 'career':
      return '일과 돈의 성향. 맞는 일 방식·환경, 재물 흐름의 장단점, 피하면 좋은 선택. 핵심 주제와 연결. 사주 근거 + 일상 예시 + 행동 힌트. 5~8문장'
    case 'yearFlow':
      return '올해(또는 최근~앞으로 1년)의 흐름. 기회·주의 시기, 재물·관계·건강 중 두드러지는 축을 중심으로. 핵심 주제와 연결. 근거 + 예시 + 올해 행동 힌트. 5~8문장'
    case 'balance':
      return '강점(살릴 것)과 주의점(막을 것)을 한 섹션에서 균형 있게. 핵심 주제와 연결. 각각 사주 근거 + 일상 예시 + 구체적 대응법. 5~8문장'
    case 'chart':
      return '년·월·일·시주, 일간, 월령, 오행 분포(과다/부족), 십신 핵심을 6~10줄로 정리. 앞 해석의 근거가 되도록 간결하게'
    default:
      return ''
  }
}
